// Tests that Extract copies only the asked-for declarations, as wire types.

package main

import (
	"testing"

	ginkgo "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
)

func TestCodegen(t *testing.T) {
	RegisterFailHandler(ginkgo.Fail)
	ginkgo.RunSpecs(t, "codegen")
}

var _ = ginkgo.Describe("Extract", func() {
	base := Options{
		Dir: "testdata/models", Files: []string{"model.go"}, Package: "wire", Source: "example.com/models@v1.2.3",
	}

	// A dropped field leaves its line blank: the printer keeps the source's line positions.
	ginkgo.It("keeps the selected types and const blocks with json and yaml tags only", func() {
		opts := base
		opts.Types = []string{"Item", "Severity"}
		opts.Consts = []string{"StatusOpen"}

		generated, err := Extract(opts)

		Expect(err).ToNot(HaveOccurred())
		Expect(string(generated)).To(Equal(`// Code generated by internal/codegen from example.com/models@v1.2.3; DO NOT EDIT.

package wire

import (
	"github.com/google/uuid"
	"github.com/lib/pq"
	"time"
)

const (
	StatusOpen   = "open"
	StatusClosed = "closed"
)

type Severity string

const (
	SeverityLow  Severity = "low"
	SeverityHigh Severity = "high"
)

// Item is a stored record.
type Item struct {
	ID uuid.UUID ` + "`json:\"id\" yaml:\"id\"`" + `
	// Labels are free-form.
	Labels   pq.StringArray ` + "`json:\"labels,omitempty\"`" + `
	Severity Severity       ` + "`json:\"severity\"`" + `
	Internal string

	CreatedAt *time.Time ` + "`json:\"created_at\"`" + `
}
`))
	})

	ginkgo.It("fails on a requested name the source does not declare", func() {
		opts := base
		opts.Types = []string{"Item", "Missing"}
		opts.Consts = []string{"StatusGone"}

		_, err := Extract(opts)

		Expect(err).To(MatchError(ContainSubstring("not declared in testdata/models: Missing, StatusGone")))
	})
})
