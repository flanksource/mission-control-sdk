// Copies selected type and const declarations out of another package's source, keeping
// only their json and yaml struct tags, so this module can carry wire types without importing
// the module that owns them. gopatch rewrites the result onto this module's own types;
// Taskfile.yaml's go:generate:models runs both.

package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"path"
	"path/filepath"
	"reflect"
	"sort"
	"strconv"
	"strings"
)

type Options struct {
	Dir     string
	Files   []string
	Types   []string
	Consts  []string
	Package string
	Source  string
}

type source struct {
	file  *ast.File
	decls []*ast.GenDecl
}

// Extract renders the selected declarations as one formatted Go file. A type or const
// that is asked for and not found is an error: a silently shorter copy would drop a wire
// field nobody notices is missing.
func Extract(opts Options) ([]byte, error) {
	if opts.Dir == "" || opts.Package == "" || len(opts.Files) == 0 || len(opts.Types) == 0 {
		return nil, fmt.Errorf("dir, package, files and types are required")
	}
	types, consts := set(opts.Types), set(opts.Consts)
	found := map[string]bool{}
	fset := token.NewFileSet()

	var sources []source
	for _, name := range opts.Files {
		file, err := parser.ParseFile(fset, filepath.Join(opts.Dir, name), nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		src := source{file: file}
		for _, decl := range file.Decls {
			if gen, ok := decl.(*ast.GenDecl); ok && keep(gen, types, consts, found) {
				src.decls = append(src.decls, gen)
			}
		}
		sources = append(sources, src)
	}
	if missing := absent(append(append([]string{}, opts.Types...), opts.Consts...), found); len(missing) > 0 {
		return nil, fmt.Errorf("not declared in %s: %s", opts.Dir, strings.Join(missing, ", "))
	}

	imports, err := usedImports(sources)
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by internal/codegen from %s; DO NOT EDIT.\n\npackage %s\n\n", opts.Source, opts.Package)
	if len(imports) > 0 {
		out.WriteString("import (\n")
		for _, imported := range imports {
			fmt.Fprintf(&out, "\t%s\n", imported)
		}
		out.WriteString(")\n\n")
	}
	for _, src := range sources {
		for _, decl := range src.decls {
			if err := printer.Fprint(&out, fset, decl); err != nil {
				return nil, err
			}
			out.WriteString("\n\n")
		}
	}
	return format.Source(out.Bytes())
}

// keep narrows a type declaration to the wanted specs and reports whether anything is
// left. A const block is kept whole when it names a wanted const or a wanted type.
func keep(gen *ast.GenDecl, types, consts, found map[string]bool) bool {
	switch gen.Tok {
	case token.TYPE:
		var specs []ast.Spec
		for _, spec := range gen.Specs {
			typeSpec := spec.(*ast.TypeSpec)
			if types[typeSpec.Name.Name] {
				found[typeSpec.Name.Name] = true
				stripTags(typeSpec.Type)
				specs = append(specs, spec)
			}
		}
		gen.Specs = specs
		return len(specs) > 0
	case token.CONST:
		kept := false
		for _, spec := range gen.Specs {
			value := spec.(*ast.ValueSpec)
			if ident, ok := value.Type.(*ast.Ident); ok && types[ident.Name] {
				kept = true
			}
			for _, name := range value.Names {
				if consts[name.Name] {
					found[name.Name] = true
					kept = true
				}
			}
		}
		return kept
	}
	return false
}

// stripTags drops unexported fields, fields JSON never encodes, and every struct tag key
// but json and yaml: the copy is a wire type, and the database and fixture tags describe
// someone else's storage.
func stripTags(expr ast.Expr) {
	structType, ok := expr.(*ast.StructType)
	if !ok {
		return
	}
	var fields []*ast.Field
	for _, field := range structType.Fields.List {
		if len(field.Names) > 0 && !field.Names[0].IsExported() || jsonOmitted(field.Tag) {
			continue
		}
		if field.Tag != nil {
			field.Tag = wireTag(field.Tag)
		}
		fields = append(fields, field)
	}
	structType.Fields.List = fields
}

func jsonOmitted(tag *ast.BasicLit) bool {
	if tag == nil {
		return false
	}
	raw, err := strconv.Unquote(tag.Value)
	return err == nil && reflect.StructTag(raw).Get("json") == "-"
}

// wireTagKeys are the encodings a wire type is read and written with.
var wireTagKeys = []string{"json", "yaml"}

func wireTag(tag *ast.BasicLit) *ast.BasicLit {
	raw, err := strconv.Unquote(tag.Value)
	if err != nil {
		return tag
	}
	var parts []string
	for _, key := range wireTagKeys {
		if value, ok := reflect.StructTag(raw).Lookup(key); ok {
			parts = append(parts, key+":"+strconv.Quote(value))
		}
	}
	if len(parts) == 0 {
		return nil
	}
	return &ast.BasicLit{ValuePos: tag.ValuePos, Kind: token.STRING, Value: "`" + strings.Join(parts, " ") + "`"}
}

// usedImports returns the import lines the kept declarations reference, failing on a
// qualifier none of the source files imports.
func usedImports(sources []source) ([]string, error) {
	lines := map[string]bool{}
	for _, src := range sources {
		byName := map[string]string{}
		for _, spec := range src.file.Imports {
			importPath, _ := strconv.Unquote(spec.Path.Value)
			if spec.Name != nil {
				byName[spec.Name.Name] = spec.Name.Name + " " + spec.Path.Value
			} else {
				byName[path.Base(importPath)] = spec.Path.Value
			}
		}
		var missing error
		for _, decl := range src.decls {
			ast.Inspect(decl, func(node ast.Node) bool {
				selector, ok := node.(*ast.SelectorExpr)
				if !ok {
					return true
				}
				if qualifier, ok := selector.X.(*ast.Ident); ok {
					line, imported := byName[qualifier.Name]
					if !imported {
						missing = fmt.Errorf("%s.%s: no import named %s", qualifier.Name, selector.Sel.Name, qualifier.Name)
						return false
					}
					lines[line] = true
				}
				return true
			})
		}
		if missing != nil {
			return nil, missing
		}
	}
	out := make([]string, 0, len(lines))
	for line := range lines {
		out = append(out, line)
	}
	sort.Strings(out)
	return out, nil
}

func set(values []string) map[string]bool {
	out := make(map[string]bool, len(values))
	for _, value := range values {
		out[value] = true
	}
	return out
}

func absent(wanted []string, found map[string]bool) []string {
	var missing []string
	for _, name := range wanted {
		if !found[name] {
			missing = append(missing, name)
		}
	}
	return missing
}
